--[[ Goblin Gazette - Core/Audio.lua
	Every sound goes through here; the stage and the window never play a file themselves. The files and
	their lengths come from Data/Sound.lua (generated by gg_build_audio.py, mix gains baked in).

	  Au:Play(name)          a sound effect (Sound Effects channel); a short per-sound cooldown, so a burst
	                         of the same event plays once
	  Au:Loop(slot, name) / Au:StopLoop(slot)    a looped bed (the engine, the street's ambience), kept
	                         going by Au:Update; started again only when it isn't already playing
	  Au:Music(name)         a loop through the game's music player (menu, results); the same one again does
	                         nothing
	  Au:Ride(danger)        the riding theme: the route mix, or the chase mix while danger is true. The two
	                         are one piece in two mixes; the switch waits for the next 2-bar line and plays
	                         the other mix from that same place (pre-cut rotations: the music player can't
	                         seek), so the chase comes in on the beat instead of starting over
	  Au:Stinger(name)       a one-shot on the Music channel (perfect, record, fail); results music after
	  Au:StopMusic(), Au:Halt()   (Halt: the music and the beds, the window closed)
	  Au:Update(now)         once a frame while the window is open: loops, the theme switch, what's queued

	Settings: "sound" (effects and beds) and "music" (both default on). ]]

local _, ns = ...
local P = ns.P
local Au = P:Module("Audio")
local S = ns.Sound

local ROOT = P.MEDIA
local GetTime = GetTime
local floor = math.floor

local COOLDOWN = { swerve = 0.35, brake = 0.3, engine_rev = 0.3, score_tick = 0.06, horn = 1.0, chaser_alert = 0.4 }
local DEFAULT_COOLDOWN = 0.05
local EARLY = 0.015          -- a looped bed is started again this much before it ends: no gap at the seam

local lastAt, handles = {}, {}
local paths = {}

local function Path(rel)
	local p = paths[rel]
	if not p then
		p = ROOT .. rel:gsub("/", "\\") .. ".ogg"
		paths[rel] = p
	end
	return p
end

function Au:SoundOn() return P:Setting("sound") ~= false end
function Au:MusicOn() return P:Setting("music") ~= false end

local function PlayFile(path, channel)
	if type(PlaySoundFile) ~= "function" then return nil end
	local t0 = P:ProfStart()
	local ok, willPlay, handle = pcall(PlaySoundFile, path, channel)
	P:ProfEnd("sound", t0)
	if ok and willPlay then return handle or true end
	return nil
end

local function Stop(handle, fadeMs)
	if handle and handle ~= true and type(StopSound) == "function" then pcall(StopSound, handle, fadeMs) end
end

-- ------------------------------------------------------------------ effects
function Au:Play(name)
	if not self:SoundOn() then return false end
	local s = S.sfx[name]
	if not s then return false end
	local now = GetTime()
	local last = lastAt[name]
	if last and now - last < (COOLDOWN[name] or DEFAULT_COOLDOWN) then return false end
	lastAt[name] = now
	local h = PlayFile(Path(s[1]), s[2])
	if h and h ~= true then
		handles[#handles + 1] = h
		if #handles > 16 then table.remove(handles, 1) end
	end
	return h ~= nil
end

function Au:Cancel()
	for i = 1, #handles do Stop(handles[i]) end
	wipe(handles)
end

-- ------------------------------------------------------------------ looped beds
local loops = {}             -- slot -> { name, handle, nextAt }

function Au:Loop(slot, name)
	if not self:SoundOn() then return end
	local l = loops[slot]
	if l and l.name == name then return end
	if l then Stop(l.handle, 150) end
	local s = S.loops[name]
	if not s then return end
	l = l or {}
	l.name, l.nextAt = name, 0           -- starts on the next Update
	l.handle = nil
	loops[slot] = l
end

function Au:StopLoop(slot, fadeMs)
	local l = loops[slot]
	if not l then return end
	Stop(l.handle, fadeMs or 150)
	loops[slot] = nil
end

function Au:Looping(slot) return loops[slot] ~= nil end

-- ------------------------------------------------------------------ music
-- the music player plays one file at a time and loops it; zone music comes back after StopMusic
local playing                -- what the music player is on: a music name, or "route"/"chase" while riding
local ride                   -- the riding theme: { want, cur, base, t0 } (base: the piece's place at t0)
local queued                 -- { at, name }: music to start after a stinger

local function PlayMusicFile(rel)
	if type(PlayMusic) ~= "function" then return false end
	local t0 = P:ProfStart()
	pcall(PlayMusic, Path(rel))
	P:ProfEnd("music", t0)
	return true
end

function Au:Music(name)
	queued = nil
	ride = nil
	if not self:MusicOn() then return end
	local m = S.music[name]
	if not m or playing == name then return end
	if PlayMusicFile(m[1]) then playing = name end
end

local TH = S.themes
local function Rotation(mix, k) return TH[mix] .. ("%02d"):format(k) end

-- where the riding theme is now, in seconds into the piece
local function Place(now)
	local p = ride.base + (now - ride.t0)
	return p - floor(p / TH.length) * TH.length
end

function Au:Ride(danger)
	if not self:MusicOn() then return end
	local want = danger and "chase" or "route"
	if ride then
		ride.want = want
		return
	end
	-- the ride starts: the route mix from the top (or the chase mix, if a chase is already on)
	queued = nil
	ride = { want = want, cur = want, base = 0, t0 = GetTime() }
	PlayMusicFile(Rotation(want, 0))
	playing = want
end

function Au:Riding() return ride ~= nil end
function Au:Mix() return ride and ride.cur end

function Au:Stinger(name, after)
	ride = nil
	queued = nil
	if not self:MusicOn() then return end
	if playing and type(StopMusic) == "function" then StopMusic() end
	playing = nil
	local s = S.stingers[name]
	if s then PlayFile(Path(s[1]), "Music") end
	if after then queued = { at = GetTime() + (s and s[2] or 0) + 0.3, name = after } end
end

function Au:StopMusic()
	ride, queued = nil, nil
	if playing and type(StopMusic) == "function" then StopMusic() end
	playing = nil
end

function Au:Halt()
	self:StopMusic()
	for slot in pairs(loops) do self:StopLoop(slot, 0) end
end

-- ------------------------------------------------------------------ the frame
function Au:Update(now)
	now = now or GetTime()
	-- beds: start the next pass just before this one ends
	for _, l in pairs(loops) do
		if now >= l.nextAt then
			local s = S.loops[l.name]
			l.handle = PlayFile(Path(s[1]), s[2])
			l.nextAt = now + s[3] - EARLY
		end
	end
	-- the theme: swap mixes on a 2-bar line, at the same place in the piece
	if ride and ride.want ~= ride.cur then
		local p = Place(now)
		local k = floor(p / TH.step)
		local into = p - k * TH.step
		local last = ride.lastK
		if last == nil then ride.lastK = k
		elseif k ~= last or TH.step - into < 0.017 then
			-- on (or just past) the line: the other mix, from that line
			if k == last then k = (k + 1) % TH.rotations end
			k = k % TH.rotations
			ride.cur, ride.base, ride.t0, ride.lastK = ride.want, k * TH.step, now, nil
			PlayMusicFile(Rotation(ride.cur, k))
			playing = ride.cur
		end
	elseif ride then
		ride.lastK = nil
	end
	if queued and now >= queued.at then
		local name = queued.name
		queued = nil
		self:Music(name)
	end
end
