--[[ Goblin Gazette - Core/Assets.lua
	Game code asks for sprites and animation frames by name and never builds a file path.
	The names and rectangles come from Data/Atlas.lua (generated by the asset build).

	  A:Sprite(tex, name [, flip])      texture + texcoords; returns the sprite's drawn size
	  A:Coords(tex, name [, flip])      texcoords only (same atlas: an animation's next frame)
	  A:Rect(name)                      file, u0, u1, v0, v1 (for 9-slices)
	  A:Has(name) / A:Size(name)
	  A:Anim(name)                      { fps, loop, w, h, px, py, frame names... } or nil
	  A:Ground(zone)                    the zone's ground picture path
	  A:Trim()                          forget unpacked records (the window closed)
	  A.missing                         problems found (shown by /gazette debug) ]]

local _, ns = ...
local P = ns.P
local A = P:Module("Assets")
local D = ns.Atlas
local TEX = P.MEDIA .. "Tex\\"

A.missing = {}
A.TEX = TEX

local spr, animSrc = D.spr, D.anim
local tex = {}
for i, t in ipairs(D.tex) do tex[i] = t end

local function Missing(what)
	if #A.missing < 40 then A.missing[#A.missing + 1] = what end
end

-- Data/Atlas.lua keeps each sprite as one packed number and each animation as one short string; a record
-- is unpacked the first time it is drawn and kept until the window closes, so the closed game holds only
-- the compact manifest.
local recs, anims = {}, {}
local floor = math.floor

local function Rec(name)
	local r = recs[name]
	if r then return r end
	local v = spr[name]
	if not v then return nil end
	local h = v % 2048 v = floor(v / 2048)
	local w = v % 4096 v = floor(v / 4096)
	local y = v % 4096 v = floor(v / 4096)
	local x = v % 4096
	local t = tex[floor(v / 4096)]
	local aw, ah = t[2], t[3]
	r = { TEX .. t[1], x, y, w, h, x / aw, (x + w) / aw, y / ah, (y + h) / ah }
	recs[name] = r
	return r
end

local function FrameName(name, i) return ("%s_%02d"):format(name, i) end

-- every frame of every animation must exist: checked once at load, listed rather than drawn blank
for name, src in pairs(animSrc) do
	local n = tonumber(src:match("(%d+)$")) or 0
	if n < 1 then Missing("animation " .. name .. " has no frames") end
	for i = 1, n do
		if not spr[FrameName(name, i)] then Missing("animation " .. name .. " frame " .. i) end
	end
end

function A:Has(name) return spr[name] ~= nil end
function A:Size(name)
	local s = Rec(name)
	if s then return s[4], s[5] end
	return 0, 0
end

function A:Sprite(t, name, flip)
	local s = Rec(name)
	if not s then
		Missing("sprite " .. tostring(name))
		t:SetColorTexture(1, 0, 1, 0.5)
		return 8, 8
	end
	t:SetTexture(s[1])
	if flip then t:SetTexCoord(s[7], s[6], s[8], s[9]) else t:SetTexCoord(s[6], s[7], s[8], s[9]) end
	return s[4], s[5]
end

-- the sprite's file and texcoord rectangle (u0, u1, v0, v1): for slicing a sprite into pieces
function A:Rect(name)
	local s = Rec(name)
	if not s then return nil end
	return s[1], s[6], s[7], s[8], s[9]
end

function A:Coords(t, name, flip)
	local s = Rec(name)
	if not s then return end
	if flip then t:SetTexCoord(s[7], s[6], s[8], s[9]) else t:SetTexCoord(s[6], s[7], s[8], s[9]) end
end

-- { fps, loop, w, h, px, py, frame names... }
function A:Anim(name)
	local a = anims[name]
	if a then return a end
	local src = animSrc[name]
	if not src then return nil end
	local fps, loop, w, h, px, py, n = src:match("^(%S+) (%d) (%d+) (%d+) (%S+) (%S+) (%d+)$")
	a = { fps = tonumber(fps), loop = loop == "1", w = tonumber(w), h = tonumber(h), px = tonumber(px), py = tonumber(py) }
	for i = 1, tonumber(n) do a[i] = FrameName(name, i) end
	anims[name] = a
	return a
end

function A:Ground(zone) return TEX .. "G_" .. zone end

function A:Trim()
	wipe(recs)
	wipe(anims)
end
